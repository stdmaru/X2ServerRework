#!/usr/bin/env python3
"""Generates flags/<x>.generated.toml from a build profile. Usage: tools/import/gen_flags.py server"""

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from x2import import condres, flagsim, pipeline, profile, textio  # noqa: E402

_COND_RE = re.compile(r"^\s*#\s*(if|ifdef|ifndef|elif)\b(.*)$")
_DEFINE_RE = re.compile(r"^\s*#\s*define\s+([A-Za-z_]\w*)(\()?")
_IDENT_RE = re.compile(r"\b[A-Za-z_]\w*\b")


def checked_read(path: Path) -> bytes:
    data = path.read_bytes()
    pipeline._check_integrity(path, data)
    return data


def scan_code(root: Path, files: list[Path], config: set[Path]):
    """Identifiers used in conditionals, and macros #defined outside the config headers (name -> files)."""
    used: Counter[str] = Counter()
    local: dict[str, set[str]] = {}
    for p in files:
        try:
            text = textio.normalize(textio.decode(checked_read(p)).text)
        except pipeline.ImportError_ as e:
            print(f"warning: skipped {e}", file=sys.stderr)
            continue
        in_comment = False
        for _, line in condres._logical_lines(text):
            starts_in_comment = in_comment
            in_comment = condres._scan_comment_state(line, in_comment)
            if starts_in_comment:
                continue
            m = _COND_RE.match(line)
            if m:
                code, _ = condres._strip_comments(m.group(2))
                for ident in _IDENT_RE.findall(code):
                    if ident != "defined":
                        used[ident] += 1
                continue
            if p in config:
                continue
            m = _DEFINE_RE.match(line)
            if m and not m.group(2):
                local.setdefault(m.group(1), set()).add(p.relative_to(root).as_posix())
    return used, local, len(files)


def toml_list(names) -> str:
    items = sorted(names)
    if not items:
        return "[]"
    return "[\n" + "".join(f'    "{n}",\n' for n in items) + "]"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("profile", help="flags/<profile>.profile.toml")
    args = ap.parse_args()

    pr = profile.load(args.profile)
    prof, root = pr.data, pr.root
    service = pr.simulate(dev=False, read=checked_read)
    dev = pr.simulate(dev=True, read=checked_read)

    config = pr.config
    universe: set[str] = set()
    funcs: set[str] = set()
    for p in sorted(config):
        names, f = flagsim.scan_mentions(p, read=checked_read)
        universe |= names
        funcs |= f
    universe |= service.mentioned | dev.mentioned
    # build-system / platform macros that configuration headers happen to define (WINVER, STRICT, ...)
    not_flags = set(prof.get("not_flags", []))
    universe -= not_flags

    used, local, scanned = scan_code(root, pr.files(), config)
    prefixes = tuple(prof["flag_prefixes"])
    used_flags = {n for n in used if n.startswith(prefixes)} - not_flags

    # names handled elsewhere: environment/country/tool flags (base.toml) and build-system macros
    base_flags = pipeline.load_flags(["base"])
    handled = base_flags.true | base_flags.false | base_flags.dev | base_flags.dev_not
    build_macros = set(pr.defines) | set(pr.dev_defines)

    locals_ = {n for n in local if n in universe | used_flags}  # flags (re)defined by ordinary code
    candidates = (universe | used_flags) - funcs - handled - build_macros - locals_

    svc = {n for n in service.defined if n in candidates}
    dev_scope = (universe | used_flags) - funcs - build_macros - locals_ - (handled - base_flags.dev)
    dev_only = {n for n in dev.defined if n in dev_scope} - set(service.defined)
    dev_whitelist = base_flags.dev
    true = svc
    false = candidates - svc
    valued = {n: service.defined[n] for n in svc if service.defined[n]}

    rel = lambda p: p.resolve().relative_to(root).as_posix()  # noqa: E731
    ref = lambda p: p.resolve().relative_to(pipeline.REFERENCE.resolve()).as_posix()  # noqa: E731
    entries = ", ".join(ref(e) for e in pr.entries)
    out = pipeline.TOOL / "flags" / prof["output"]
    out.write_text(
        f"# GENERATED by tools/import/gen_flags.py {args.profile} - do not edit.\n"
        f"# Source: _reference/X2Server: {entries} with {', '.join(pr.defines)}.\n"
        f"# Overrides go in a hand-written file loaded after this one (see flags/{args.profile}.toml).\n\n"
        f"[{args.profile}_generated]\n"
        f"true = {toml_list(true)}\n\n"
        f"false = {toml_list(false)}\n")

    rep_dir = pipeline.TOOL / "reports" / prof["report"]
    rep_dir.mkdir(parents=True, exist_ok=True)
    dev_defs = " ".join(pr.dev_defines) + "".join(f" -{d}" for d in pr.dev_undefines)
    L = [f"# Flags report: `{args.profile}`", "", "Generated by `tools/import/gen_flags.py`. Do not edit by hand.", "",
         f"- entries (in order): " + ", ".join(f"`{ref(e)}`" for e in pr.entries)
         + f"; defines: `{' '.join(pr.defines)}`; dev: `{dev_defs}`",
         f"- config headers visited: " + ", ".join(f"`{rel(p)}`" for p in service.files),
         f"- **true: {len(true)}**, **false: {len(false)}** (universe {len(universe)}, flags used in code {len(used_flags)}, files scanned {scanned})",
         ""]
    L += ["## Defined only in the development build", "",
          "Whitelisted names become `X2_DEV_TOOLS`; the others are discarded (resolved as in the service build).", ""]
    L += [f"- `{n}` " + ("**-> X2_DEV_TOOLS**" if n in dev_whitelist else "-> false") for n in sorted(dev_only)] or ["(none)"]
    L += ["", "## Flags with a value", "", "Resolved only through `defined()`; `#if NAME` comparisons are kept.", ""]
    L += [f"- `{n}` = `{v}`" for n, v in sorted(valued.items())] or ["(none)"]
    L += ["", "## Flags also defined in ordinary code (left unresolved)", ""]
    L += [f"- `{n}`: " + ", ".join(f"`{f}`" for f in sorted(local[n])[:5]) for n in sorted(locals_)] or ["(none)"]
    L += ["", "## Flags used in code but mentioned in no configuration header (-> false)", ""]
    orphans = sorted(used_flags - universe - locals_ - handled)
    L += [", ".join(f"`{n}`" for n in orphans) or "(none)"]
    for layer in pr.layers:
        own = pr.simulate(dev=False, read=checked_read, entries=layer.entries)
        lused, _, lscanned = scan_code(root, [f for f in pr.files(layer.code_globs) if f.resolve() not in config], config)
        diff = sorted(n for n in lused if n in candidates and (n in own.defined) != (n in service.defined))
        L += ["", f"## Layer `{layer.name}`", "",
              f"Reads only {', '.join(f'`{rel(e)}`' for e in layer.entries)} ({lscanned} files besides configuration "
              "headers). Flags tested in its code whose value there differs from the profile's (the generated value "
              "changes that code compared with the original layer):", ""]
        L += [f"- `{n}`: layer {'true' if n in own.defined else 'false'}, profile {'true' if n in service.defined else 'false'}"
              for n in diff] or ["(none)"]
    L += ["", "## Simulation warnings", ""]
    warn = [f"- unresolved include `{i}` in `{rel(p)}`" for p, i in service.unresolved_includes]
    warn += [f"- `{rel(p)}:{n}` unsupported condition `{t}` (treated as false)" for p, n, t in service.unsupported]
    L += warn or ["(none)"]
    L.append("")
    (rep_dir / "REPORT.md").write_text("\n".join(L))

    print(f"{out.relative_to(pipeline.REPO)}: {len(true)} true, {len(false)} false; "
          f"report: {(rep_dir / 'REPORT.md').relative_to(pipeline.REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
