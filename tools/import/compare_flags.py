#!/usr/bin/env python3
"""Lists the flags whose value differs between two flag profiles in the code both of them compile.

Shared code (server `Common` headers that the client also includes: packets, event IDs, enums) can be
resolved only once if it lives in one place, so every flag tested there with a different server and client
value is a conflict to settle. Each conflict line shows where the flag is tested, and whether a packet
definition (a `#pragma pack` file or a `*Packet*` file) depends on it.

Usage: tools/import/compare_flags.py server client [--report reports/flags-shared/REPORT.md]
"""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from x2import import condres, pipeline, profile, textio  # noqa: E402

_COND_RE = re.compile(r"^\s*#\s*(if|ifdef|ifndef|elif)\b(.*)$")
_IDENT_RE = re.compile(r"\b[A-Za-z_]\w*\b")


def value(flags: condres.Flags, name: str) -> str:
    st = flags.state(name)
    return {"dev": "X2_DEV_TOOLS", "dev_not": "!X2_DEV_TOOLS", None: "unknown"}.get(st, st)


def tested(path: Path) -> dict[str, list[int]]:
    text = textio.normalize(textio.decode(path.read_bytes()).text)
    out: dict[str, list[int]] = {}
    in_comment = False
    for lineno, line in condres._logical_lines(text):
        starts = in_comment
        in_comment = condres._scan_comment_state(line, in_comment)
        if starts:
            continue
        m = _COND_RE.match(line)
        if m:
            code, _ = condres._strip_comments(m.group(2))
            for ident in _IDENT_RE.findall(code):
                if ident != "defined":
                    out.setdefault(ident, []).append(lineno)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("a", help="first profile (e.g. server)")
    ap.add_argument("b", help="second profile (e.g. client)")
    ap.add_argument("--report", help="write a Markdown report to this path (relative to tools/import)")
    args = ap.parse_args()

    pa, pb = profile.load(args.a), profile.load(args.b)

    def flags_of(name: str) -> condres.Flags:
        names = ["base", f"{name}.generated", name]
        return pipeline.load_flags([n for n in names if (pipeline.TOOL / "flags" / f"{n}.toml").exists()])

    fa, fb = flags_of(args.a), flags_of(args.b)
    shared = sorted(set(pa.files()) & set(pb.files()) - pa.config - pb.config)
    ref = lambda p: p.resolve().relative_to(pipeline.REFERENCE.resolve()).as_posix()  # noqa: E731

    conflicts: dict[str, list[tuple[str, list[int], bool]]] = {}
    for p in shared:
        text = p.read_bytes()
        packet = b"#pragma pack" in text or "Packet" in p.name
        for name, lines in tested(p).items():
            va, vb = value(fa, name), value(fb, name)
            if va != vb and not (va == "unknown" and vb == "unknown"):
                conflicts.setdefault(name, []).append((ref(p), lines, packet))

    L = [f"# Flag conflicts: `{args.a}` x `{args.b}`", "",
         "Generated by `tools/import/compare_flags.py`. Do not edit by hand.", "",
         f"- shared files (compiled by both, configuration headers excluded): **{len(shared)}**",
         f"- flags tested there with different values: **{len(conflicts)}** "
         f"(in packet files: {sum(any(x[2] for x in v) for v in conflicts.values())})", "",
         f"| Flag | {args.a} | {args.b} | Tested in |", "|---|---|---|---|"]
    for name in sorted(conflicts):
        where = "; ".join(f"`{f}`:{','.join(map(str, ls[:6]))}{' (packet)' if pk else ''}" for f, ls, pk in conflicts[name])
        L.append(f"| `{name}` | {value(fa, name)} | {value(fb, name)} | {where} |")
    L += ["", "Shared files:", "", ", ".join(f"`{ref(p)}`" for p in shared), ""]
    report = "\n".join(L)
    if args.report:
        out = pipeline.TOOL / args.report
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(report)
        print(f"{out.relative_to(pipeline.REPO)}: {len(conflicts)} conflicts in {len(shared)} shared files")
    else:
        print(report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
