#!/usr/bin/env python3
"""Generates the round-trip tests of every serialized type of the server's Common (packets and their parts).

For each SERIALIZE_DEFINE_PUT/GET pair it checks that PUT and GET list the same fields in the same order and
that each block only uses its own macro (the original had GET blocks calling PUT: an asymmetry breaks the protocol) and emits a call to CheckRoundTrip<T>() (see
src/server/Common/tests/packet_test.h): Put -> Get -> Put gives the same bytes and Get consumes everything.

Usage: tools/port/gen_packet_tests.py [--check]   (--check: fail if the generated files are out of date)
"""

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
COMMON = REPO / "src/server/Common"
OUT = COMMON / "tests"

# test file -> (header that declares the types, sources that define their PutInto/GetFrom)
GROUPS = {
    "client": ("ClientPacket.h", ["ClientPacket.cpp", "OnlyGlobal/Packet/ClientPacket_Global.cpp"]),
    "common": ("CommonPacket.h", ["CommonPacket.cpp", "OnlyGlobal/Packet/CommonPacket_Global.cpp"]),
    "server": ("ServerPacket.h", ["ServerPacket.cpp", "OnlyGlobal/Packet/ServerPacket_Global.cpp"]),
}

BLOCK = re.compile(r"SERIALIZE_DEFINE_(PUT|GET)\(\s*(\w+)\s*,\s*\w+\s*,\s*\w+\s*\)\s*\{(.*?)\n\}", re.S)
FIELD = re.compile(r"\b(?:PUT|GET)\(\s*([\w.\[\]]+)\s*\)")


def strip_comments(text: str) -> str:
    return re.sub(r"//[^\n]*", "", re.sub(r"/\*.*?\*/", "", text, flags=re.S))


conditions: dict[str, str] = {}  # type -> preprocessor condition of its definition (e.g. "X2_DEV_TOOLS")


def enclosing_condition(text: str, pos: int) -> str | None:
    """`#if` conditions around pos joined with &&; None if an #else/#elif is involved."""
    stack: list[str | None] = []
    for m in re.finditer(r"^[ \t]*#[ \t]*(if|ifdef|ifndef|elif|else|endif)\b(.*)$", text[:pos], re.M):
        directive, arg = m.group(1), m.group(2).strip()
        if directive == "endif":
            stack.pop()
        elif directive in ("else", "elif"):
            stack[-1] = None
        else:
            arg = {"ifdef": f"defined({arg})", "ifndef": f"!defined({arg})"}.get(directive, arg)
            stack.append(arg.split("//")[0].strip())
    if any(c is None for c in stack):
        return None
    return " && ".join(f"({c})" for c in stack)


def collect(sources: list[str]) -> tuple[list[str], list[str]]:
    puts: dict[str, list[str]] = {}
    gets: dict[str, list[str]] = {}
    order: list[str] = []
    wrong_kind: list[str] = []
    errors_pp: list[str] = []
    for src in sources:
        text = strip_comments((COMMON / src).read_text(encoding="utf-8"))  # old definitions sit in /* */
        for m in BLOCK.finditer(text):
            kind, typ, body = m.groups()
            cond = enclosing_condition(text, m.start())
            if cond is None:
                errors_pp.append(f"{typ}: #else/#elif around the definition is not supported")
            elif cond:
                conditions[typ] = cond
            fields = FIELD.findall(body)
            wrong = "GET" if kind == "PUT" else "PUT"
            if re.search(r"\b" + wrong + r"\s*\(", body):
                wrong_kind.append(f"{typ}: {wrong}() inside SERIALIZE_DEFINE_{kind}")
            if kind == "PUT":
                puts[typ] = fields
                order.append(typ)
            else:
                gets[typ] = fields
    errors = wrong_kind + errors_pp
    for typ in order:
        if typ not in gets:
            errors.append(f"{typ}: PUT without GET")
        elif puts[typ] != gets[typ]:
            errors.append(f"{typ}: PUT {puts[typ]} != GET {gets[typ]}")
    errors += [f"{typ}: GET without PUT" for typ in gets if typ not in puts]
    return order, errors


def render(group: str, header: str, types: list[str]) -> str:
    lines = [
        f"// Generated by tools/port/gen_packet_tests.py from {header}: do not edit.",
        "// Round trip of every serialized type (see packet_test.h).",
        '#include "packet_test.h"',
        "",
        f'#include "{header}"',
        "",
        f'TEST_CASE("{group} packets: Put -> Get -> Put round trip ({len(types)} types)")',
        "{",
    ]
    for t in types:
        call = f"    CheckRoundTrip<{t}>(\"{t}\");"
        lines += [f"#if {conditions[t]}", call, "#endif"] if t in conditions else [call]
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    stale, failed = [], False
    for group, (header, sources) in GROUPS.items():
        types, errors = collect(sources)
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
            failed = True
        path = OUT / f"test_packets_{group}.cpp"
        text = render(group, header, types)
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"{path.relative_to(REPO)}: {len(types)} types")
    for path in stale:
        print(f"error: {path.relative_to(REPO)} is out of date; run tools/port/gen_packet_tests.py", file=sys.stderr)
    return 1 if failed or stale else 0


if __name__ == "__main__":
    sys.exit(main())
