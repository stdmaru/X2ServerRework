#!/usr/bin/env python3
"""Compiles the project's HLSL shaders offline with SDL_shadercross (decision T39).

Each shader directory has a `shaders.json` manifest:

    {
        "output": "generated/Name.inc",
        "shaders": [
            {"name": "Vertex", "source": "File.vert.hlsl", "stage": "vertex",
             "variants": {"DEFINE": [0, 1], ...}},          # optional: one shader per combination
            ...
        ]
    }

For every shader (and variant) it produces SPIR-V, DXIL and MSL plus shadercross's reflection, and writes them as one
C++ include file that is committed next to the sources: builds never run a shader compiler. The include file records
an FNV-1a hash of the manifest and the sources; a test recomputes it and fails when a source changed without running
this tool again.

Run it in the build image, where shadercross and DXC live (x86_64 only):

    docker/build.sh python3 tools/shaders/compile.py src/client/KTDXLIB/D3D9/shaders
    docker/build.sh python3 tools/shaders/compile.py --check src/client/KTDXLIB/D3D9/shaders

See docs/tools/shaders.md.
"""

import argparse
import itertools
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

FORMATS = (("spirv", "SPIRV"), ("dxil", "DXIL"), ("msl", "MSL"))
STAGES = {"vertex": "Vertex", "fragment": "Fragment"}
SHADERCROSS_DIR = "/opt/shadercross"


def fnv1a64(data: bytes, h: int = 0xCBF29CE484222325) -> int:
    for b in data:
        h ^= b
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def source_hash(directory: Path, files: list[str]) -> int:
    """FNV-1a 64 over each file's name, a NUL, its bytes and a NUL, in order (the test does the same)."""
    h = 0xCBF29CE484222325
    for name in files:
        h = fnv1a64(name.encode() + b"\0", h)
        h = fnv1a64((directory / name).read_bytes() + b"\0", h)
    return h


def hashed_files(manifest: dict) -> list[str]:
    files = ["shaders.json"]
    for shader in manifest["shaders"]:
        if shader["source"] not in files:
            files.append(shader["source"])
    return files


def find_shadercross() -> list[str]:
    exe = shutil.which("shadercross") or os.path.join(SHADERCROSS_DIR, "shadercross")
    if not os.path.exists(exe):
        sys.exit("compile.py: shadercross not found; run this in the build image (docker/build.sh, x86_64)")
    return [exe]


def run_shadercross(cmd: list[str], env: dict) -> None:
    result = subprocess.run(cmd, env=env, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"compile.py: {' '.join(cmd)}\n{result.stdout}{result.stderr}")


def compile_variant(shadercross, env, directory, shader, defines, tmp):
    source = directory / shader["source"]
    stage = shader["stage"]
    base = [*shadercross, str(source), "-s", "HLSL", "-t", stage, "-I", str(directory)]
    base += [f"-D{k}={v}" for k, v in defines]
    out = {}
    for key, dest in FORMATS + (("json", "JSON"),):
        path = Path(tmp) / f"out.{key}"
        run_shadercross(base + ["-d", dest, "-o", str(path)], env)
        out[key] = path.read_bytes()
    reflection = json.loads(out.pop("json"))
    msl_entry = "main0" if re.search(rb"\bmain0\s*\(", out["msl"]) else "main"
    return out, reflection, msl_entry


def c_array(name: str, data: bytes) -> str:
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    return f"alignas(4) inline constexpr unsigned char {name}[] = {{\n" + "\n".join(lines) + "\n};\n"


def generate(directory: Path) -> str:
    manifest = json.loads((directory / "shaders.json").read_text())
    shadercross = find_shadercross()
    env = dict(os.environ)
    env["LD_LIBRARY_PATH"] = SHADERCROSS_DIR + (":" + env["LD_LIBRARY_PATH"] if env.get("LD_LIBRARY_PATH") else "")
    files = hashed_files(manifest)

    parts = [
        "// Generated by tools/shaders/compile.py from shaders.json (decision T39). Do not edit: change the .hlsl\n"
        "// sources and run the tool again (docs/tools/shaders.md).\n"
        "// Needs <cstdint> and x2::GeneratedShader (KTDXLIB/D3D9/GeneratedShader.h) before inclusion.\n",
        f"inline constexpr std::uint64_t kShaderSourceHash = 0x{source_hash(directory, files):016x}ULL;\n",
        "inline constexpr const char* kShaderSourceFiles[] = {"
        + ", ".join(f'"{f}"' for f in files) + "};\n",
    ]
    tables = []
    with tempfile.TemporaryDirectory() as tmp:
        for shader in manifest["shaders"]:
            variants = shader.get("variants", {})
            keys = list(variants)
            combos = list(itertools.product(*(variants[k] for k in keys))) or [()]
            entries = []
            for combo in combos:
                defines = list(zip(keys, combo))
                suffix = "".join(f"_{k}{v}" for k, v in defines)
                ident = shader["name"] + suffix
                blobs, reflection, msl_entry = compile_variant(shadercross, env, directory, shader, defines, tmp)
                for key, _ in FORMATS:
                    parts.append(c_array(f"{ident}_{key}", blobs[key]))
                label = " ".join(f"{k}={v}" for k, v in defines)
                entries.append(
                    f'    {{"{shader["name"]}", "{label}", x2::render::ShaderStage::{STAGES[shader["stage"]]},\n'
                    f"     {{{ident}_spirv, sizeof({ident}_spirv)}}, {{{ident}_dxil, sizeof({ident}_dxil)}},\n"
                    f'     {{{ident}_msl, sizeof({ident}_msl)}}, "{msl_entry}", '
                    f'{reflection["samplers"]}, {reflection["uniform_buffers"]}}},'
                )
            order = ", ".join(keys) if keys else "none"
            tables.append(
                f"// {len(entries)} variant(s); index in the order of the defines ({order}), last one fastest.\n"
                f"inline constexpr x2::GeneratedShader k{shader['name']}[] = {{\n" + "\n".join(entries) + "\n};\n"
            )
    return "\n".join(parts + tables)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("directories", nargs="+", type=Path, help="shader directories (with a shaders.json)")
    parser.add_argument("--check", action="store_true", help="fail if a generated file is not current")
    args = parser.parse_args()
    status = 0
    for directory in args.directories:
        manifest = json.loads((directory / "shaders.json").read_text())
        output = directory / manifest["output"]
        if args.check:
            # Only the hash: compiler output may differ between DXC builds without the shaders changing.
            expected = f"0x{source_hash(directory, hashed_files(manifest)):016x}ULL"
            if not output.exists() or expected not in output.read_text():
                print(f"{output}: out of date; run tools/shaders/compile.py {directory}")
                status = 1
            continue
        text = generate(directory)
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(text)
        print(f"{output}: {len(text) // 1024} KB")
    return status


if __name__ == "__main__":
    sys.exit(main())
